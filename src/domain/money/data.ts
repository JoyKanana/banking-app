function deposit(
  id: string,
  subaccountId: string,
  amount: number,
  currency: CurrencyCode,
  description: string,
  date: string,
  counterparty = 'External bank',
): BuiltTransaction {
  return buildTransaction({
    id,
    kind: 'deposit',
    amount,
    currency,
    description,
    counterparty,
    toSubaccountId: subaccountId,
    rail: 'bank',
    createdAt: date,
    postings: [
      {
        accountRef: 'external:bank-clearing',
        direction: 'debit',
        amount,
        currency,
        memo: description,
      },
      {
        accountRef: `subaccount:${subaccountId}`,
        subaccountId,
        direction: 'credit',
        amount,
        currency,
        memo: description,
      },
    ],
  })
}

function payment(
  id: string,
  subaccountId: string,
  amount: number,
  currency: CurrencyCode,
  description: string,
  date: string,
  counterparty: string,
  rail: PaymentRail = { id: 'card' } as PaymentRail,
): BuiltTransaction {
  return buildTransaction({
    id,
    kind: 'payment',
    amount,
    currency,
    description,
    counterparty,
    fromSubaccountId: subaccountId,
    rail: rail.id,
    createdAt: date,
    postings: [
      {
        accountRef: `subaccount:${subaccountId}`,
        subaccountId,
        direction: 'debit',
        amount,
        currency,
        memo: description,
      },
      {
        accountRef: `external:${rail.id}-clearing`,
        direction: 'credit',
        amount,
        currency,
        memo: description,
      },
    ],
  })
}

function transfer(
  id: string,
  fromSubaccountId: string,
  toSubaccountId: string,
  amount: number,
  currency: CurrencyCode,
  description: string,
  date: string,
): BuiltTransaction {
  return buildTransaction({
    id,
    kind: 'transfer',
    amount,
    currency,
    description,
    counterparty: 'Internal transfer',
    fromSubaccountId,
    toSubaccountId,
    rail: 'relay',
    createdAt: date,
    postings: [
      {
        accountRef: `subaccount:${fromSubaccountId}`,
        subaccountId: fromSubaccountId,
        direction: 'debit',
        amount,
        currency,
        memo: description,
      },
      {
        accountRef: `subaccount:${toSubaccountId}`,
        subaccountId: toSubaccountId,
        direction: 'credit',
        amount,
        currency,
        memo: description,
      },
    ],
  })
}

